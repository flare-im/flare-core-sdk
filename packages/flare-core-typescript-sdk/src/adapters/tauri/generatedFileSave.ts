import { invoke } from '@tauri-apps/api/core';

export const MAX_TAURI_GENERATED_FILE_BYTES = 8 * 1024 * 1024;

export interface TauriGeneratedFileSaveRequest {
  sourcePath: string;
  fileName: string;
  downloadKey: string;
}

export interface TauriGeneratedFileSaveOptions {
  signal?: AbortSignal;
}

export type TauriGeneratedFileInvoker = <T>(
  command: string,
  args?: Record<string, unknown>,
) => Promise<T>;

export type TauriGeneratedFileSaver = (
  blob: Blob,
  fileName: string,
  options?: TauriGeneratedFileSaveOptions,
) => Promise<unknown>;

const TOKEN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

function throwIfAborted(signal?: AbortSignal): void {
  if (signal?.aborted) throw new DOMException('Generated file save cancelled', 'AbortError');
}

function record(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? value as Record<string, unknown> : null;
}

function absoluteFilePath(value: unknown): value is string {
  if (typeof value !== 'string' || !value || value.length > 32_768 || /[\u0000-\u001f]/.test(value)) return false;
  if (!(value.startsWith('/') || /^[A-Za-z]:[\\/]/.test(value) || /^\\\\[^\\]+\\[^\\]+/.test(value))) return false;
  const parts = value.replace(/\\/g, '/').split('/').filter(Boolean);
  return parts.length > 0 && parts.every(part => part !== '.' && part !== '..');
}

function base64(bytes: Uint8Array): string {
  const parts: string[] = [];
  for (let offset = 0; offset < bytes.length; offset += 0x8000) {
    parts.push(String.fromCharCode(...bytes.subarray(offset, offset + 0x8000)));
  }
  return btoa(parts.join(''));
}

/**
 * Save generated bytes through the native platform adapter and an existing typed media save.
 * The caller supplies its current SDK's saveToDevice operation; there is no browser-download fallback.
 * Staged paths come only from the App-scoped native registry, and finally cleanup takes only its token.
 */
export function createTauriGeneratedFileSaver(
  saveToDevice: (request: TauriGeneratedFileSaveRequest) => Promise<unknown>,
  options: { invoke?: TauriGeneratedFileInvoker } = {},
): TauriGeneratedFileSaver {
  const nativeInvoke = options.invoke ?? invoke;
  return async (blob, fileName, saveOptions = {}) => {
    const { signal } = saveOptions;
    throwIfAborted(signal);
    if (!Number.isSafeInteger(blob.size) || blob.size <= 0 || blob.size > MAX_TAURI_GENERATED_FILE_BYTES) {
      throw new Error('Generated file is empty or too large');
    }
    if (!fileName.trim() || fileName.length > 200 || /[\u0000-\u001f/\\]/.test(fileName)) {
      throw new Error('Invalid generated file name');
    }
    const bytes = new Uint8Array(await blob.arrayBuffer());
    throwIfAborted(signal);
    if (bytes.byteLength !== blob.size) throw new Error('Generated file size changed');
    let token: string | undefined;
    try {
      throwIfAborted(signal);
      const staged = record(await nativeInvoke<unknown>('sdk_stage_generated_file', {
        bytesBase64: base64(bytes),
      }));
      // Retain a valid token before other validation so a malformed path still gets cleanup.
      if (typeof staged?.token === 'string' && TOKEN.test(staged.token)) token = staged.token;
      throwIfAborted(signal);
      if (!staged || !token || !absoluteFilePath(staged.path) || staged.sizeBytes !== bytes.byteLength) {
        throw new Error('Invalid generated file staging result');
      }
      const parts = staged.path.replace(/\\/g, '/').split('/');
      if (parts.at(-2) !== 'generated-files' || parts.at(-1) !== `generated-${token}.bin`) {
        throw new Error('Invalid generated file staging path');
      }
      throwIfAborted(signal);
      const result = await saveToDevice({
        sourcePath: staged.path,
        fileName,
        downloadKey: `generated:${token}`,
      });
      throwIfAborted(signal);
      const saved = record(result);
      if (!saved || !absoluteFilePath(saved.path) || saved.path === staged.path) {
        throw new Error('Native save did not return a saved file path');
      }
      return result;
    } finally {
      if (token) {
        try {
          // Deliberately not cancelled: even an aborted UI operation must release its staging token.
          await nativeInvoke<boolean>('sdk_cleanup_generated_file', { token });
        } catch {
          // Cleanup cannot change the already known save result or replace its original failure.
          // Never include generated bytes, token, paths or the native error in this diagnostic.
          console.warn('[Flare SDK] Generated file staging cleanup failed');
        }
      }
    }
  };
}
